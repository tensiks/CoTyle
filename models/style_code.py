"""Style code -> style token sequence for the prior (StyleGenerator).

Two schemes:

* ``original``: CoTyle's sampling, with the style code used as the RNG seed. Neighbouring
  codes give unrelated token sequences.
* ``ordered``: neighbouring codes give neighbouring token sequences.
    - The 196-token sequence (a 14 x 14 grid) is split into ``num_sections`` equal sections.
    - The style code is written as one level in [0, num_levels) per section with a reflected
      Gray code, so codes N and N+1 differ in exactly one section, by exactly one level.
    - Each section is generated by the prior without the other sections: it continues a fixed,
      unbiased anchor sequence (the same for all codes) from the section's first position, so
      it sits at its true rows of the grid with plausible context before it.
      An additive logit bias boosts a Gaussian window of the codebook tokens sorted along a
      1-D order (see notebooks/codebook_token_ordering.ipynb). Neighbouring levels boost
      overlapping windows.
    - The sampling noise (Gumbel-max) depends only on the section index, not on its level,
      so a one-level change only flips the tokens whose top choices were close.
    - A section therefore depends only on (section, level), and the
      num_sections * num_levels chunks are cached.
"""

import copy
import os

import numpy as np
import torch

from .utils import set_seed

SEQ_LEN = 196  # 14 x 14 style tokens

# Sampling settings of the original CoTyle style generation (shared by both schemes).
TEMPERATURE = 1.0
TOP_K = 200
TOP_P = 0.95
REPETITION_PENALTY = 50.0

DEFAULT_TOKEN_ORDER = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "notebooks", "outputs", "token_order_pca.npy",
)


def reflected_gray(n, base, num_digits):
    """Write n (< base**num_digits) as base-`base` digits in reflected Gray order, most significant first.

    n and n+1 differ in exactly one digit, by exactly 1.
    """
    digits = []
    for i in range(num_digits - 1, -1, -1):
        p = base ** i
        d, n = divmod(n, p)
        if d % 2 == 1:  # odd digit -> the lower block is traversed in reverse
            n = p - 1 - n
        digits.append(d)
    return digits


def load_token_rank(path, vocab_size):
    """rank[token] = position of the token in the saved 1-D order, -1 for tokens left out of it."""
    order = np.load(path).astype(np.int64)
    if len(np.unique(order)) != len(order) or order.min() < 0 or order.max() >= vocab_size:
        raise ValueError(f"{path} is not an order over distinct token ids in [0, {vocab_size})")
    rank = np.full(vocab_size, -1, dtype=np.int64)
    rank[order] = np.arange(len(order))
    return rank


def level_bias_table(rank, num_levels, sigma, strength):
    """(num_levels, vocab) additive logit bias: one Gaussian bump over the token order per level.

    `sigma` is the bump width in level spacings; tokens outside the order get no bias.
    """
    spacing = (rank >= 0).sum() / num_levels
    centres = (torch.arange(num_levels, dtype=torch.float32) + 0.5) * spacing
    r = torch.from_numpy(rank).float()
    bias = strength * torch.exp(-((r[None] - centres[:, None]) ** 2) / (2 * (sigma * spacing) ** 2))
    bias[:, torch.from_numpy(rank < 0)] = 0.0
    return bias


def filter_top_k_top_p(logits, top_k, top_p):
    """Set logits outside the top-k / nucleus (top-p) set to -inf, as HF's TopK/TopP warpers do."""
    logits = logits.clone()
    if top_k < logits.numel():
        kth = torch.topk(logits, top_k).values[-1]
        logits[logits < kth] = -float("inf")
    sorted_logits, sorted_idx = torch.sort(logits, descending=True)
    probs = sorted_logits.softmax(-1)
    remove = probs.cumsum(-1) - probs > top_p  # keep the smallest set reaching top_p (always >= 1 token)
    logits[sorted_idx[remove]] = -float("inf")
    return logits


def apply_repetition_penalty(logits, prev_ids, penalty):
    """HF's repetition penalty: divide positive / multiply negative logits of tokens already generated."""
    score = logits[prev_ids]
    logits[prev_ids] = torch.where(score < 0, score * penalty, score / penalty)
    return logits


class OrderedStyleCode:
    """Maps an integer style code to a (1, 196) style token sequence so that nearby codes give nearby sequences."""

    def __init__(self, prior, code_freq, freq_threshold, freq_k, token_order=DEFAULT_TOKEN_ORDER,
                 num_sections=7, num_levels=10, level_sigma=1.0, bias_strength=3.0, noise_seed=0, use_anchor=True):
        if SEQ_LEN % num_sections:
            raise ValueError(f"num_sections must divide {SEQ_LEN}, got {num_sections}")
        self.prior = prior
        self.forward_kwargs = dict(code_freq=code_freq, code_freq_threshold=freq_threshold, k=freq_k)
        self.device = next(prior.parameters()).device
        self.vocab_size = prior.config.vocab_size
        self.num_sections = num_sections
        self.num_levels = num_levels
        self.section_len = SEQ_LEN // num_sections
        self.noise_seed = noise_seed
        self.use_anchor = use_anchor

        self.rank = load_token_rank(token_order, self.vocab_size)
        self.bias = level_bias_table(self.rank, num_levels, level_sigma, bias_strength).to(self.device)
        self.ranked = torch.from_numpy(self.rank >= 0).to(self.device)
        self._chunks = {}
        self._anchor_states = None

    @property
    def capacity(self):
        """Number of distinct styles; codes are taken modulo this."""
        return self.num_levels ** self.num_sections

    def levels(self, style_code):
        return reflected_gray(style_code % self.capacity, self.num_levels, self.num_sections)

    def __call__(self, style_code):
        return torch.cat([self.chunk(s, v) for s, v in enumerate(self.levels(style_code))], dim=1)

    def chunk(self, section, level):
        """Tokens of `section` at `level`, generated after the anchor's tokens before that section."""
        key = (section, level)
        if key not in self._chunks:
            state = self.anchor_states()[section - 1] if self.use_anchor and section else None
            gumbel = self._gumbel(section, self.section_len)  # same noise for every level of a section
            self._chunks[key], _ = self._sample(self.bias[level], gumbel, state)
        return self._chunks[key]

    def anchor_states(self):
        """Sampler states of the anchor at the start of sections 1, 2, ...

        The anchor is an unbiased reference sequence shared by all codes; it gives each section a
        plausible context. It uses the sections' own noise, and each section continues from the
        anchor's exact state (KV cache included), so an unbiased section reproduces the anchor and
        the context mismatch after stitching grows only as far as the bias moves a section away.
        """
        if self._anchor_states is None:
            gumbel = torch.cat([self._gumbel(s, self.section_len) for s in range(self.num_sections)])
            _, self._anchor_states = self._sample(torch.zeros_like(self.bias[0]), gumbel,
                                                  snapshot_every=self.section_len)
        return self._anchor_states

    def _gumbel(self, stream, length):
        g = torch.Generator().manual_seed(self.noise_seed * 1000 + stream)
        u = torch.rand(length, self.vocab_size, generator=g, dtype=torch.float64)
        return (-torch.log(-torch.log(u.clamp_min(1e-300)))).float().to(self.device)

    @torch.no_grad()
    def _sample(self, bias, gumbel, state=None, snapshot_every=0):
        """Gumbel-max sample len(gumbel) tokens with the prior.

        `state` is a snapshot (past_key_values, history, next_input) to continue from; None starts from
        scratch. Also returns a snapshot taken before every `snapshot_every`-th token (none if 0).
        """
        if state is None:
            # No context to condition on (CoTyle draws this token uniformly): sample it from the bias alone.
            first = torch.where(self.ranked, bias, -float("inf"))
            tokens = [torch.argmax(first + gumbel[0])]
            past, history, next_input = None, tokens[0].view(1), tokens[0].view(1, 1)
        else:
            tokens = []
            past, history, next_input = copy.deepcopy(state)  # the model extends the KV cache in place

        snapshots = []
        for t in range(len(tokens), len(gumbel)):
            if snapshot_every and t % snapshot_every == 0:
                snapshots.append(copy.deepcopy((past, history, next_input)))
            # logits_to_keep=1 so StyleGenerator.forward's frequency suppression hits the predicted position.
            out = self.prior(input_ids=next_input, past_key_values=past, use_cache=True, logits_to_keep=1,
                             **self.forward_kwargs)
            past = out.past_key_values
            logits = apply_repetition_penalty(out.logits[0, -1].float(), history, REPETITION_PENALTY)
            logits = filter_top_k_top_p(logits / TEMPERATURE + bias, TOP_K, TOP_P)
            tokens.append(torch.argmax(logits + gumbel[t]))
            history, next_input = torch.cat([history, tokens[-1].view(1)]), tokens[-1].view(1, 1)
        return torch.stack(tokens).view(1, -1), snapshots


@torch.no_grad()
def original_style_ids(prior, style_code, code_freq, freq_threshold, freq_k):
    """CoTyle's style generation: the style code seeds the RNG, then the prior samples 195 tokens."""
    set_seed(style_code)
    input_ids = torch.randint(low=0, high=1024, size=(1, 1)).to(prior.device)
    return prior.generate(
        input_ids=input_ids,
        attention_mask=torch.ones(input_ids.shape).to(prior.device),
        max_new_tokens=SEQ_LEN - 1,
        temperature=TEMPERATURE,
        top_k=TOP_K,
        top_p=TOP_P,
        do_sample=True,
        repetition_penalty=REPETITION_PENALTY,
        code_freq=code_freq,
        code_freq_threshold=freq_threshold,
        k=freq_k,
    )


def add_style_code_args(parser):
    group = parser.add_argument_group("style code")
    group.add_argument("--style_mode", choices=["ordered", "original", "file"], default="ordered",
                       help="ordered: nearby codes give nearby styles; original: CoTyle sampling seeded by the "
                            "style code; file: load the token ids from --style_ids_path")
    group.add_argument("--style_ids_path", type=str, default="generated_ids.pt")
    group.add_argument("--token_order", type=str, default=DEFAULT_TOKEN_ORDER,
                       help="1-D order of the codebook tokens (.npy of token ids)")
    group.add_argument("--num_sections", type=int, default=7, help="sections of the 196 tokens; must divide 196")
    group.add_argument("--num_levels", type=int, default=10, help="levels per section")
    group.add_argument("--level_sigma", type=float, default=1.0, help="bias bump width, in level spacings")
    group.add_argument("--bias_strength", type=float, default=3.0, help="peak additive logit bias")
    group.add_argument("--noise_seed", type=int, default=0, help="seed of the anchor and per-section sampling noise")
    group.add_argument("--no_anchor", action="store_true",
                       help="generate every section from scratch instead of after the anchor's earlier tokens")
    return group


def make_style_ids_fn(args, prior, code_freq):
    """Return style_code -> (1, 196) token ids for the scheme chosen by --style_mode."""
    if args.style_mode == "file":
        return lambda style_code: torch.load(args.style_ids_path)
    if args.style_mode == "original":
        return lambda style_code: original_style_ids(prior, style_code, code_freq, args.freq_threshold, args.freq_k)
    return OrderedStyleCode(prior, code_freq, args.freq_threshold, args.freq_k, token_order=args.token_order,
                            num_sections=args.num_sections, num_levels=args.num_levels,
                            level_sigma=args.level_sigma, bias_strength=args.bias_strength,
                            noise_seed=args.noise_seed, use_anchor=not args.no_anchor)
